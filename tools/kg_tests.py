#!/usr/bin/env python3
"""
Knowledge-graph validation tests A–F on the real database (brief 2026-11-02 §05).

  python3 -I tools/kg_tests.py            # -> eval/kg-tests-<date>.md, exit 1 on any FAIL

Reads brain/data/kg.json, relations.json, plants/*.json only (run tools/pipeline.py first). Each test states what it
checks, the evidence it found and PASS / FAIL / WARN. Nothing is hand-written: every line is read from the graph.
  A  Classification   every plant has a genus → family path and a growth-form classification read from sources (M29)
  B  Shared knowledge every pair of plants shares ≥ 1 knowledge node reached through claims; the shared node is traceable to
                      claims with source and status on both sides
  C  Direct relations survey co-listing and other direct relations are separate from shared-concept (indirect) links, carry a
                      source and status, and retired relations are not counted as direct links
  D  Design knowledge every plant → design-concept edge is derived (KG-R1 use mapping with a claim) or candidate / unknown
                      (KG-R4 trait check) — never documented; every design concept cites a literature source
  E  Evidence         every claim edge resolves to a claim with source, status and verification; disagreements and variation
                      are listed with their claim ids; retired / model claims are not live
  F  Extensibility    tools/scale_test.py --n 1 builds an 11-plant root through the same pipeline with no interface change
Standard library only.
"""
import json, os, subprocess, sys
from collections import defaultdict
from datetime import date
from itertools import combinations

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.environ.get("PLANTING_DB_ROOT") or os.path.dirname(HERE)
J = lambda p: json.load(open(os.path.join(ROOT, p), encoding="utf-8"))
KG, REL = J("brain/data/kg.json"), J("relations.json")
N = {n["id"]: n for n in KG["nodes"]}; E = KG["edges"]; C = KG["claims"]
PLANTS = sorted(n["id"] for n in KG["nodes"] if n["type"] == "plant")
label = lambda i: N[i]["label"] if i in N else i
TODAY = date.today().isoformat()
out = [f"# Knowledge-graph tests A–F · {TODAY}", "", f"Generated by `python3 -I tools/kg_tests.py` from `brain/data/kg.json` ({KG['counts']['plants']} plants · {KG['counts']['nodes']} nodes · {KG['counts']['edges']} edges · {KG['counts']['claims']} claims; ontology {KG['ontology_version']}, schema {KG['schema_version']}). Every line is read from the graph; nothing is hand-written.", ""]
results = {}


def section(t, title): out.append(f"## Test {t} — {title}"); out.append("")
def verdict(t, ok, warn=False):
    results[t] = "WARN" if warn and ok else ("PASS" if ok else "FAIL"); out.append(f"**{results[t]}**"); out.append("")


# ---------------------------------------------------------------- A
section("A", "Classification: taxonomy and growth form from the data")
ok = True
out.append("| plant | genus → family | growth form | status | evidence (sources) | KPU plant type |"); out.append("|---|---|---|---|---|---|")
for p in PLANTS:
    gen = next((e for e in E if e["type"] == "taxonomy" and e["source"] == p), None)
    fam = next((e for e in E if e["type"] == "taxonomy" and gen and e["source"] == gen["target"]), None)
    cls = next((e for e in E if e["type"] == "classification" and e["source"] == p), None)
    gf = KG["growth_forms"].get(p.split(":")[1], {})
    if not (gen and fam and cls): ok = False
    out.append(f"| {label(p)} | {label(gen['target']) if gen else '—'} → {label(fam['target']) if fam else '—'} | {label(cls['target']) if cls else '—'} | {gf.get('status', '—')} | {', '.join(gf.get('evidence', {}).keys()) or '—'}{' (weak: ' + ', '.join(gf['weak']) + ')' if gf.get('weak') else ''} | {N[p].get('plant_type')} |")
out.append("")
to_confirm = [p for p in PLANTS if KG["growth_forms"].get(p.split(":")[1], {}).get("status") == "to confirm"]
out.append(f"Growth form is read from sources (M29), never from the KPU type alone: {len(PLANTS) - len(to_confirm)} supported, {len(to_confirm)} to confirm ({', '.join(label(p) for p in to_confirm) or 'none'}). The survey role (groundcover / shrub / perennial_grass) is kept raw on the entity and counts only as one vote.")
out.append("")
verdict("A", ok, warn=bool(to_confirm))

# ---------------------------------------------------------------- B
section("B", "Shared knowledge: two plants connected through real knowledge nodes")
knowledge = [e for e in E if e.get("live") and e.get("target") and e["type"] in ("claim", "entity", "classification", "height_band", "layer", "taxonomy")]
targets = defaultdict(lambda: defaultdict(list))
for e in knowledge: targets[e.get("plant") or e["source"]][e["target"]].append(e)
pairs = {tuple(pp["plants"]): pp for pp in KG["plant_pairs"]}
ok = True; rows = []
for a, b in combinations(PLANTS, 2):
    shared = sorted(set(targets[a]) & set(targets[b]), key=lambda c: -(len(targets[a][c]) + len(targets[b][c])))
    sourced = [c for c in shared if any(e["type"] == "claim" for e in targets[a][c]) and any(e["type"] == "claim" for e in targets[b][c])]
    if not shared: ok = False
    pp = pairs.get((a, b)) or pairs.get((b, a)) or {}
    rows.append((a, b, len(shared), len(sourced), pp.get("n_shared"), sourced[:1]))
out.append("| pair | shared nodes (kg plant_pairs) | shared through claims on both sides | example node ← claim a / claim b |"); out.append("|---|---|---|---|")
for a, b, ns, nsrc, kgn, ex in sorted(rows, key=lambda r: -r[3])[:45]:
    exs = ""
    if ex:
        c = ex[0]; ea = next(e for e in targets[a][c] if e["type"] == "claim"); eb = next(e for e in targets[b][c] if e["type"] == "claim")
        exs = f"{label(c)} ← `{ea['claim_id']}` ({ea['source_id']}, {ea['status']}) / `{eb['claim_id']}` ({eb['source_id']}, {eb['status']})"
    out.append(f"| {label(a)} × {label(b)} | {kgn} | {nsrc} | {exs} |")
n_pairs = len(rows); zero = [r for r in rows if r[3] == 0]
out.append(""); out.append(f"{n_pairs} pairs; {n_pairs - len(zero)} share at least one node reached by sourced claims on both sides; {len(zero)} share none through claims ({', '.join(f'{label(a)} × {label(b)}' for a, b, *_ in zero) or 'none'}). A shared node is an indirect connection: it never says the two plants combine (kg plant_pairs text says so on every pair).")
out.append("")
verdict("B", ok, warn=bool(zero))

# ---------------------------------------------------------------- C
section("C", "Plant-to-plant relations: direct vs indirect, retired excluded")
rels = [e for e in E if e["type"] == "relation"]
live_rels = [e for e in rels if e.get("verification") != "retired"]
retired = [e for e in rels if e.get("verification") == "retired"]
by_kind = defaultdict(int)
for e in live_rels: by_kind[(e["rel"], e["kg_status"], e.get("source_type"))] += 1
out.append("| relation | kg status | source type | n |"); out.append("|---|---|---|---|")
for (r, s, st), n in sorted(by_kind.items()): out.append(f"| {r} | {s} | {st} | {n} |")
out.append("")
pair_direct = {tuple(sorted(pp["plants"])): pp for pp in KG["plant_pairs"]}
leak = [pp for pp in KG["plant_pairs"] for d in pp["direct_relations"] if d.get("verification") == "retired"]
no_src = [e for e in live_rels if not e.get("source_id") or e["kg_status"] not in ("documented", "derived", "candidate")]
indirect_only = [pp for pp in KG["plant_pairs"] if pp["n_shared"] >= 5 and not pp["direct_relations"]]
out.append(f"Live relations: {len(live_rels)} ({sum(1 for e in live_rels if e['rel'] == 'co_listed')} survey co-listings, {sum(1 for e in live_rels if e['kg_status'] == 'derived')} rule-derived, {sum(1 for e in live_rels if e['kg_status'] == 'candidate')} model placeholders kept as candidates). Retired relations: {len(retired)} — counted in plant_pairs as direct links: {len(leak)} (must be 0). Relations without source or with an unknown status: {len(no_src)}.")
out.append(f"Pairs that share ≥ 5 knowledge nodes but have NO direct relation (indirect only, shown as such): {len(indirect_only)} — e.g. {', '.join(f'{label(pp['plants'][0])} × {label(pp['plants'][1])} ({pp['n_shared']})' for pp in indirect_only[:5])}.")
for e in live_rels[:40]: out.append(f"- `{e['id']}` {label(e['source'])} —{e['rel']}→ {label(e['target'])} · {e['kg_status']} · {e.get('source_id')} · {e.get('verification')}" + (f" · rule {e['basis'].get('rule')}" if e.get('basis', {}).get('rule') else ""))
out.append("")
verdict("C", not leak and not no_src and bool(live_rels))

# ---------------------------------------------------------------- D
section("D", "Design knowledge: sourced or explicitly derived, never asserted")
design = [e for e in E if e["type"] == "design"]
doc_design = [e for e in design if e["kg_status"] == "documented"]
z_nodes = [n for n in KG["nodes"] if n.get("dimension") == "design"]
z_nosrc = [n for n in z_nodes if not n.get("source_of_term")]
by = defaultdict(int)
for e in design: by[e["kg_status"]] += 1
out.append(f"Design (plant → concept) edges: {dict(by)}; documented (forbidden): {len(doc_design)}. Design concepts: {len(z_nodes)}, without a literature source: {len(z_nosrc)}.")
out.append(""); out.append("| plant | derived (KPU use → concept, with claim) | candidate (all required traits met) | unknown / contradicted |"); out.append("|---|---|---|---|")
for p in PLANTS:
    mine = [e for e in design if e["source"] == p]
    d = [label(e["target"]) for e in mine if e["kg_status"] == "derived"]; c = [label(e["target"]) for e in mine if e["kg_status"] == "candidate"]; u = [f"{label(e['target'])} ({e['verdict']})" for e in mine if e["kg_status"] == "unknown"]
    out.append(f"| {label(p)} | {', '.join(d) or '—'} | {', '.join(c) or '—'} | {len(u)}: {'; '.join(u[:4])}{'…' if len(u) > 4 else ''} |")
layers = [e for e in E if e["type"] == "layer"]
out.append(""); out.append(f"Vertical layers (KG-R5: growth form forms the layer ∧ a height claim reaches a band it corresponds to): " + "; ".join(f"{label(e['source'])} → {label(e['target'])}" for e in layers) + ".")
concepts_without = KG["gaps"]["design_concepts_without_plants"]
out.append(f"Design concepts no plant reaches: {', '.join(g['label'] for g in concepts_without) or 'none'}. Relations to confirm at page level: {len(KG['gaps']['relations_to_confirm'])}.")
out.append("")
verdict("D", not doc_design and not z_nosrc)

# ---------------------------------------------------------------- E
section("E", "Evidence and conflicts: every link traceable to claims, sources and status")
claim_edges = [e for e in E if e["type"] == "claim"]
bad = [e for e in claim_edges if e.get("live") and (e.get("claim_id") not in C or not e.get("source_id") or e.get("verification") not in ("verified", "unverified", "disputed"))]
live_model = [e for e in claim_edges if e.get("live") and (e.get("source_type") == "model" or C.get(e.get("claim_id"), {}).get("status") == "retired")]
ver = defaultdict(int)
for cid, c in C.items():
    if c.get("kind") == "relation": continue
    ver[c.get("status")] += 1
dis = KG["conflicts"]["disagreement"]; var = KG["conflicts"]["variation"]; uvt = KG["conflicts"]["design_use_vs_traits"]
out.append(f"Claims in the index: {sum(ver.values())} — by status {dict(ver)}. Live claim edges: {sum(1 for e in claim_edges if e.get('live'))}; with a missing claim / source / verification: {len(bad)}; live edges from model or retired claims: {len(live_model)} (must be 0).")
out.append(f"Disagreements (same plant + facet, no stated condition, different sources, disjoint values): {len(dis)}; condition-dependent variation: {len(var)}; KPU-use vs trait contradictions: {len(uvt)}; single-source plant–concept links: {KG['gaps']['single_source_links']}.")
out.append(""); out.append("Disagreements (first 25):")
for d in dis[:25]: out.append(f"- {d['text']}  (`{d['claims'][0]}` ↔ `{d['claims'][1]}`)")
out.append(""); out.append("Variation with stated conditions:")
for v in var: out.append(f"- {v['text']}")
out.append(""); out.append("Gate facets with no sourced claim:")
for g in KG["gaps"]["gate_facet_missing"]: out.append(f"- {g['text']}")
out.append("")
verdict("E", not bad and not live_model)

# ---------------------------------------------------------------- F
section("F", "Extensibility: an 11th plant through the same pipeline")
r = subprocess.run([sys.executable, "-I", os.path.join(HERE, "scale_test.py"), "--n", "1"], capture_output=True, text=True, env=dict(os.environ))
okF = r.returncode == 0 and "FAILED" not in r.stdout
root = os.path.join(ROOT, "tests", "scale", "out", "db-1", "brain", "data", "kg.json")
if okF and os.path.exists(root):
    kg1 = json.load(open(root, encoding="utf-8")); synth = [n for n in kg1["nodes"] if n["type"] == "plant" and "synth" in n["id"]]
    s = synth[0]["id"] if synth else None
    es = [e for e in kg1["edges"] if (e.get("plant") or e["source"]) == s]
    out.append(f"`tools/scale_test.py --n 1`: root with {kg1['counts']['plants']} plants built by the unchanged pipeline ({kg1['counts']['nodes']} nodes, {kg1['counts']['edges']} edges). The synthetic 11th plant {label(s) if s in N else s} got: growth form {kg1['growth_forms'].get(s.split(':')[1], {}).get('form')} ({kg1['growth_forms'].get(s.split(':')[1], {}).get('status')}), {sum(1 for e in es if e['type'] == 'taxonomy')} taxonomy edge, {sum(1 for e in es if e['type'] == 'claim')} claim edges, {sum(1 for e in es if e['type'] == 'height_band')} height-band edges, {sum(1 for e in es if e['type'] == 'layer')} layer edge(s), {sum(1 for e in es if e['type'] == 'design' and e['kg_status'] != 'unknown')} derived/candidate design links, and pairs with all {kg1['counts']['plants'] - 1} other plants in plant_pairs: {sum(1 for pp in kg1['plant_pairs'] if s in pp['plants'])}. No interface file was edited (the brain reads kg.json only).")
else:
    out.append("scale_test failed:\n```\n" + r.stdout[-1500:] + r.stderr[-800:] + "\n```")
out.append("")
verdict("F", okF)

# ---------------------------------------------------------------- summary
out.insert(4, "| test | result |\n|---|---|\n" + "\n".join(f"| {t} | {results[t]} |" for t in "ABCDEF") + "\n")
path = os.path.join(ROOT, "eval", f"kg-tests-{TODAY}.md"); open(path, "w", encoding="utf-8").write("\n".join(out))
print(" ".join(f"{t}:{results[t]}" for t in "ABCDEF"), "->", os.path.relpath(path, ROOT))
sys.exit(1 if "FAIL" in results.values() else 0)
